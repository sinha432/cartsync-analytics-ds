export function formatCurrency(amount, settings = loadAppSettings()) {
  const numericAmount = Number(amount);
  const safeAmount = Number.isFinite(numericAmount) ? numericAmount : 0;
  const convertedAmount = safeAmount * (DEMO_CURRENCY_RATES[settings.currency] ?? 1);
  const locale = localeByLanguage[settings.language] ?? "en-IN";

  return new Intl.NumberFormat(locale, {
    style: "currency",
    currency: settings.currency,
    minimumFractionDigits: 2,
    maximumFractionDigits: 2
  }).format(convertedAmount);
}

export function toBaseCurrency(amount, settings = loadAppSettings()) {
  const rate = DEMO_CURRENCY_RATES[settings.currency] ?? 1;
  const numericAmount = Number(amount);
  return Number.isFinite(numericAmount) ? numericAmount / rate : 0;
}

export function fromBaseCurrency(amount, settings = loadAppSettings()) {
  const rate = DEMO_CURRENCY_RATES[settings.currency] ?? 1;
  const numericAmount = Number(amount);
  return Number.isFinite(numericAmount) ? numericAmount * rate : 0;
}

export function formatDate(value, settings = loadAppSettings(), options = {}) {
  const date = value instanceof Date ? value : new Date(value);
  if (Number.isNaN(date.getTime())) return "";

  const locale = localeByLanguage[settings.language] ?? "en-IN";
  if (options.month === "short" || options.month === "long") {
    return new Intl.DateTimeFormat(locale, {
      month: options.month,
      ...(options.year ? { year: "numeric" } : {})
    }).format(date);
  }

  const digits = new Intl.NumberFormat(locale, { useGrouping: false });
  const day = digits.format(date.getDate()).padStart(2, "0");
  const month = digits.format(date.getMonth() + 1).padStart(2, "0");
  const year = digits.format(date.getFullYear());

  if (settings.dateFormat === "MM/DD/YYYY") return `${month}/${day}/${year}`;
  if (settings.dateFormat === "YYYY-MM-DD") return `${year}-${month}-${day}`;
  return `${day}/${month}/${year}`;
}